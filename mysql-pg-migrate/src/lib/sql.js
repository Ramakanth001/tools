function quoteIdentifier(name) {
  return `"${String(name || '').replace(/"/g, '""')}"`;
}

function qualifyTable(schema, table) {
  return `${quoteIdentifier(schema)}.${quoteIdentifier(table)}`;
}

function buildInsertSql({ schema, table, columns, rows, conflictKeys = [], updateColumns = [], mode = 'append' }) {
  if (!rows.length) throw new Error('No rows provided for insert');
  if (!columns.length) throw new Error('No columns provided for insert');

  const values = [];
  const tuples = rows.map((row, rowIndex) => {
    const placeholders = columns.map((column, colIndex) => {
      values.push(row[column]);
      return `$${rowIndex * columns.length + colIndex + 1}`;
    });
    return `(${placeholders.join(', ')})`;
  });

  const quotedColumns = columns.map(quoteIdentifier).join(', ');
  let sql = `INSERT INTO ${qualifyTable(schema, table)} (${quotedColumns}) VALUES ${tuples.join(', ')}`;

  if (mode === 'upsert') {
    if (!conflictKeys.length) throw new Error(`Upsert mode requires conflict keys for ${schema}.${table}`);
    const quotedConflict = conflictKeys.map(quoteIdentifier).join(', ');
    const writableColumns = updateColumns.length ? updateColumns : columns.filter((column) => !conflictKeys.includes(column));
    if (!writableColumns.length) {
      sql += ` ON CONFLICT (${quotedConflict}) DO NOTHING`;
    } else {
      sql += ` ON CONFLICT (${quotedConflict}) DO UPDATE SET ${writableColumns.map((column) => `${quoteIdentifier(column)} = EXCLUDED.${quoteIdentifier(column)}`).join(', ')}`;
    }
  }

  return { sql, values };
}

function buildCreateTableSql({ schema, table, columns, primaryKey = [] }) {
  if (!columns.length) throw new Error('No columns provided for create table');
  const definitions = columns.map((column) => {
    const parts = [quoteIdentifier(column.name), column.pgType];
    if (column.generated) return `${quoteIdentifier(column.name)} ${column.pgType}`;
    if (column.identity) {
      parts.push('GENERATED BY DEFAULT AS IDENTITY');
    }
    if (!column.nullable) parts.push('NOT NULL');
    if (column.defaultExpression) parts.push(`DEFAULT ${column.defaultExpression}`);
    return parts.join(' ');
  });
  if (primaryKey.length) {
    definitions.push(`PRIMARY KEY (${primaryKey.map(quoteIdentifier).join(', ')})`);
  }
  return `CREATE TABLE IF NOT EXISTS ${qualifyTable(schema, table)} (\n  ${definitions.join(',\n  ')}\n)`;
}

function buildAlterTableAddColumnsSql({ schema, table, columns }) {
  if (!Array.isArray(columns) || !columns.length) return null;
  const actions = columns.map((column) => {
    const parts = [`ADD COLUMN IF NOT EXISTS ${quoteIdentifier(column.name)} ${column.pgType}`];
    if (!column.generated) {
      if (column.identity) parts.push('GENERATED BY DEFAULT AS IDENTITY');
      if (!column.nullable) parts.push('NOT NULL');
      if (column.defaultExpression) parts.push(`DEFAULT ${column.defaultExpression}`);
    }
    return parts.join(' ');
  });
  return `ALTER TABLE ${qualifyTable(schema, table)}\n  ${actions.join(',\n  ')}`;
}

function buildAlterTableAddConstraintSql({ schema, table, constraints = [] }) {
  if (!Array.isArray(constraints) || !constraints.length) return [];
  return constraints.map((constraint) => {
    if (constraint.type === 'unique' && constraint.columns?.length) {
      return `ALTER TABLE ${qualifyTable(schema, table)} ADD CONSTRAINT ${quoteIdentifier(constraint.name)} UNIQUE (${constraint.columns.map(quoteIdentifier).join(', ')})`;
    }
    if (constraint.type === 'foreign_key' && constraint.columns?.length && constraint.references?.table && constraint.references?.columns?.length) {
      return `ALTER TABLE ${qualifyTable(schema, table)} ADD CONSTRAINT ${quoteIdentifier(constraint.name)} FOREIGN KEY (${constraint.columns.map(quoteIdentifier).join(', ')}) REFERENCES ${qualifyTable(schema, constraint.references.table)} (${constraint.references.columns.map(quoteIdentifier).join(', ')})`;
    }
    if (constraint.type === 'check' && constraint.expression) {
      return `ALTER TABLE ${qualifyTable(schema, table)} ADD CONSTRAINT ${quoteIdentifier(constraint.name)} CHECK (${constraint.expression})`;
    }
    return null;
  }).filter(Boolean);
}

module.exports = { quoteIdentifier, qualifyTable, buildInsertSql, buildCreateTableSql, buildAlterTableAddColumnsSql, buildAlterTableAddConstraintSql };